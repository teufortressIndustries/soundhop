"""systemd user service and XDG autostart helpers."""

from __future__ import annotations

import logging
import os
import subprocess
import sys
from pathlib import Path
from typing import Any

from .constants import APP_NAME, APP_SLUG, VERSION
from .util import ensure_dir

log = logging.getLogger(__name__)

UNIT_NAME = "soundhop.service"
AUTOSTART_NAME = "soundhop-tray.desktop"


WINREG_RUN_KEY = r"Software\Microsoft\Windows\CurrentVersion\Run"
WINREG_APP_NAME = "SoundHop"


def windows_autostart_command() -> str:
    exe = python_executable()
    if getattr(sys, "frozen", False):
        return f'"{exe}" tray'
    p = Path(exe)
    pythonw = p.with_name("pythonw.exe")
    runner = str(pythonw) if pythonw.is_file() else str(p)
    return f'"{runner}" -m soundhop tray'


def winreg_query_run(name: str = WINREG_APP_NAME) -> str | None:
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, WINREG_RUN_KEY, 0, winreg.KEY_QUERY_VALUE
        ) as key:
            val, _ = winreg.QueryValueEx(key, name)
            return str(val)
    except Exception:
        return None


def winreg_write_run(name: str = WINREG_APP_NAME, command: str | None = None) -> bool:
    cmd = command or windows_autostart_command()
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, WINREG_RUN_KEY, 0, winreg.KEY_SET_VALUE
        ) as key:
            winreg.SetValueEx(key, name, 0, winreg.REG_SZ, cmd)
        return True
    except Exception:
        return False


def winreg_delete_run(name: str = WINREG_APP_NAME) -> bool:
    try:
        import winreg

        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, WINREG_RUN_KEY, 0, winreg.KEY_SET_VALUE
        ) as key:
            winreg.DeleteValue(key, name)
        return True
    except Exception:
        return False


def windows_startup_dir() -> Path:
    return (
        Path(os.environ.get("APPDATA", Path.home() / "AppData" / "Roaming"))
        / "Microsoft"
        / "Windows"
        / "Start Menu"
        / "Programs"
        / "Startup"
    )


def windows_startup_path() -> Path:
    return windows_startup_dir() / "soundhop-tray.vbs"


def windows_startup_text() -> str:
    exe = python_executable().replace('"', "")
    args = " tray" if getattr(sys, "frozen", False) else " -m soundhop tray"
    return (
        f'Set WshShell = CreateObject("WScript.Shell")\r\n'
        f'WshShell.Run chr(34) & "{exe}" & chr(34) & "{args}", 0\r\n'
        f"Set WshShell = Nothing\r\n"
    )


def systemd_dir() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "systemd" / "user"


def unit_path() -> Path:
    return systemd_dir() / UNIT_NAME


def autostart_dir() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "autostart"


def autostart_path() -> Path:
    return autostart_dir() / AUTOSTART_NAME


def unit_installed() -> bool:
    return unit_path().exists()


def package_root() -> Path:
    return Path(__file__).resolve().parent.parent


def python_executable() -> str:
    return sys.executable


def _quote_exec(value: str) -> str:
    if any(ch.isspace() for ch in value):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return value


def unit_text() -> str:
    appimage = os.environ.get("APPIMAGE")
    if appimage:
        exec_start = f"{_quote_exec(appimage)} daemon"
        env_lines = "Environment=PYTHONUNBUFFERED=1"
    else:
        root = package_root()
        exec_start = " ".join(
            _quote_exec(part) for part in (python_executable(), "-m", "soundhop", "daemon")
        )
        env_lines = (
            f"Environment=PYTHONUNBUFFERED=1\nEnvironment=PYTHONPATH={_quote_exec(str(root))}"
        )

    return f"""# Generated by SoundHop {VERSION}
[Unit]
Description={APP_NAME} local audio sharing
After=pipewire-pulse.service pipewire.service wireplumber.service
Wants=pipewire-pulse.service
PartOf=graphical-session.target

[Service]
Type=simple
ExecStart={exec_start}
{env_lines}
Restart=on-failure
RestartSec=5
TimeoutStopSec=10

[Install]
WantedBy=default.target
"""


def autostart_text() -> str:
    appimage = os.environ.get("APPIMAGE")
    if appimage:
        exec_line = f"{_quote_exec(appimage)} tray"
    else:
        exec_line = " ".join(
            _quote_exec(part) for part in (python_executable(), "-m", "soundhop", "tray")
        )
    return f"""[Desktop Entry]
Type=Application
Version=1.0
Name={APP_NAME}
Comment=Share audio with devices on your local network
Exec={exec_line}
Terminal=false
Icon={APP_SLUG}
Categories=AudioVideo;Audio;Network;
StartupNotify=false
X-GNOME-Autostart-enabled=true
"""


def _systemctl(*args: str, timeout: float = 20.0) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["systemctl", "--user", *args],
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def systemctl_available() -> bool:
    try:
        result = _systemctl("show-environment", timeout=5.0)
    except (OSError, subprocess.TimeoutExpired):
        return False
    return result.returncode == 0


def daemon_reload() -> bool:
    try:
        return _systemctl("daemon-reload").returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def install(
    *,
    enable: bool = True,
    start: bool = True,
    tray: bool = False,
) -> dict[str, Any]:
    if sys.platform == "win32":
        should_install = tray or enable
        tray_written = install_tray_autostart() if should_install else False
        has_reg = winreg_query_run() is not None
        unit_label = "Windows Registry (HKCU Run)" if has_reg else "Windows Startup Folder"
        tray_target = winreg_query_run() or (
            str(windows_startup_path()) if windows_startup_path().exists() else ""
        )
        return {
            "unit": unit_label,
            "daemon_reloaded": False,
            "enabled": tray_written,
            "started": False,
            "tray_autostart": tray_target if tray_written else "",
        }
    ensure_dir(systemd_dir())
    path = unit_path()
    path.write_text(unit_text(), encoding="utf-8")
    path.chmod(0o644)
    reloaded = daemon_reload()
    enabled = enable_service() if enable else False
    started = start_service() if start else False
    tray_written = install_tray_autostart() if tray else False
    return {
        "unit": str(path),
        "daemon_reloaded": reloaded,
        "enabled": enabled,
        "started": started,
        "tray_autostart": str(autostart_path()) if tray_written else "",
    }


def uninstall(*, remove_tray: bool = True) -> dict[str, Any]:
    if sys.platform == "win32":
        tray_removed = remove_tray_autostart() if remove_tray else False
        return {
            "unit": "Windows Autostart",
            "stopped": False,
            "disabled": False,
            "removed": tray_removed,
            "daemon_reloaded": False,
            "tray_removed": tray_removed,
        }
    stopped = stop_service()
    disabled = disable_service()
    removed = False
    try:
        if unit_path().exists():
            unit_path().unlink()
            removed = True
    except OSError:
        pass
    daemon_reload()
    tray_removed = remove_tray_autostart() if remove_tray else False
    return {
        "stopped": stopped,
        "disabled": disabled,
        "unit_removed": removed,
        "tray_autostart_removed": tray_removed,
    }


def enable_service() -> bool:
    try:
        return _systemctl("enable", UNIT_NAME).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def disable_service() -> bool:
    try:
        return _systemctl("disable", UNIT_NAME).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def start_service() -> bool:
    try:
        return _systemctl("start", UNIT_NAME).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def stop_service() -> bool:
    try:
        return _systemctl("stop", UNIT_NAME).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def restart_service() -> bool:
    try:
        return _systemctl("restart", UNIT_NAME).returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def service_status() -> dict[str, Any]:
    if sys.platform == "win32":
        reg_entry = winreg_query_run()
        file_entry = windows_startup_path().exists()
        autostart_active = bool(reg_entry or file_entry)
        return {
            "installed": autostart_active,
            "loaded": autostart_active,
            "active": autostart_active,
            "sub": "active" if autostart_active else "dead",
            "enabled": "enabled" if autostart_active else "disabled",
            "running": autostart_active,
            "main_pid": "",
            "since": "",
            "result": "",
        }
    status: dict[str, Any] = {
        "systemd": systemctl_available(),
        "installed": unit_installed(),
        "unit": str(unit_path()),
        "active": False,
        "enabled": False,
        "state": "not installed",
    }
    if not status["systemd"]:
        return status
    try:
        active = _systemctl("is-active", UNIT_NAME, timeout=5.0)
        enabled = _systemctl("is-enabled", UNIT_NAME, timeout=5.0)
        status["active"] = active.stdout.strip() == "active"
        status["enabled"] = enabled.stdout.strip() == "enabled"
        status["state"] = active.stdout.strip() or "unknown"
        show = _systemctl(
            "show",
            UNIT_NAME,
            "--property=MainPID,ActiveEnterTimestamp,Result",
            timeout=5.0,
        )
        properties: dict[str, str] = {}
        for line in show.stdout.splitlines():
            if "=" in line:
                key, value = line.split("=", 1)
                properties[key] = value
        status.update(
            {
                "main_pid": properties.get("MainPID", ""),
                "since": properties.get("ActiveEnterTimestamp", ""),
                "result": properties.get("Result", ""),
            }
        )
    except (OSError, subprocess.TimeoutExpired):
        pass
    return status


def install_tray_autostart() -> bool:
    if sys.platform == "win32":
        if winreg_write_run():
            try:
                if windows_startup_path().exists():
                    windows_startup_path().unlink()
            except OSError:
                pass
            return True
        try:
            ensure_dir(windows_startup_dir())
            windows_startup_path().write_text(windows_startup_text(), encoding="utf-8")
            return True
        except OSError:
            return False
    ensure_dir(autostart_dir())
    try:
        autostart_path().write_text(autostart_text(), encoding="utf-8")
        autostart_path().chmod(0o644)
        return True
    except OSError:
        return False


def remove_tray_autostart() -> bool:
    if sys.platform == "win32":
        removed = winreg_delete_run()
        try:
            if windows_startup_path().exists():
                windows_startup_path().unlink()
                removed = True
        except OSError:
            pass
        return removed
    try:
        if autostart_path().exists():
            autostart_path().unlink()
            return True
    except OSError:
        pass
    return False


def tray_dependency_available() -> bool:
    try:
        import PySide6  # noqa: F401
    except ModuleNotFoundError:
        return False
    return True


